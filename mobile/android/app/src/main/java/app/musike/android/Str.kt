/** Arabic counts: one, two, 3 to 10 (plural), 11 and up (singular). */
private fun ar(n: Int, one: String, two: String, few: String, many: String) = when {
    n == 1 -> one
    n == 2 -> two
    n % 100 in 3..10 -> "$n $few"
    else -> "$n $many"
}

